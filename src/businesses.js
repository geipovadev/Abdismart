/** Convierte 50689814520 en «+506 8981 4520» para mostrarlo en una conversación. */
export function formatWhatsapp(value) {
  const digits = String(value || '').replace(/\D/g, '');
  if (!digits) return '';
  if (digits.length === 11 && digits.startsWith('506')) {
    return `+506 ${digits.slice(3, 7)} ${digits.slice(7)}`;
  }
  return `+${digits}`;
}
